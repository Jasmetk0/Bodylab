'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const dir = path.resolve(__dirname, '..', 'src');
const ctx={console,structuredClone,Date,Intl,Number,String,Math,Map,JSON};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(dir,'seed.js'),'utf8')+'\n'+fs.readFileSync(path.join(dir,'math.js'),'utf8')+`
function testExports(){return {makeInitialData,weightStats,goalProgress,parseWeightCSV,safeData,serializeCSV,dailyMoving,trailing}}`,ctx);
const {makeInitialData,weightStats,goalProgress,parseWeightCSV,safeData,serializeCSV,dailyMoving,trailing}=ctx.testExports();
const fresh=makeInitialData();
assert.equal(fresh.weights.length,0,'Never embed personal weights');
assert.equal(fresh.inbodies.length,0,'Never embed personal InBody');
assert.equal(fresh.nutrition.length,0,'Never embed personal nutrition');
assert.equal(fresh.goals.length,0,'Goals must be imported privately');
assert.equal(weightStats([]).latest,null);
assert.equal(weightStats([]).avg7,null);
const weights=Array.from({length:7},(_,i)=>({date:'2026-01-'+String(i+1).padStart(2,'0'),kg:65+i*.2,note:'',creatine:'unknown'}));
assert.ok(Math.abs(weightStats(weights).avg7-65.6)<1e-9);
assert.equal(trailing(weights,7,'2026-01-07').length,7);
assert.ok(Math.abs(dailyMoving(weights).at(-1).avg-65.6)<1e-9);
assert.ok(Math.abs(goalProgress(65,70,67)-40)<1e-8);
const imported=parseWeightCSV('Datum;Váha\n08.01.2026;66,5\n09.01.2026;66,8');
assert.equal(imported.rows.length,2);
assert.equal(imported.rows[0].kg,66.5);
assert.equal(parseWeightCSV('date,kg\n2026-01-10,67.2').rows[0].kg,67.2);
assert.equal(parseWeightCSV('datum;vaha\n2026-02-30;80').errors.length,1);
const obj={...fresh,weights,inbodies:[{date:'2026-01-01',source:'Test',smm:31.5,slm:null,icw:null,lean:{leftArm:3.1},fat:{}}],goals:[{id:'test',name:'Demo',due:'',historic:false,metrics:{weight:70,smm:35},lean:{},fat:{}}],nutrition:[{date:'2026-01-01',kcal:3000,protein:140,carbs:360,fat:95}],events:[{date:'2026-01-03',label:'Workout',type:'training'}]};
const parsed=safeData(JSON.parse(JSON.stringify(obj)));
assert.equal(parsed.inbodies[0].slm,null);
assert.equal(parsed.inbodies[0].icw,null);
assert.equal(parsed.goals[0].metrics.weight,70);
assert.equal(parsed.nutrition[0].kcal,3000);
assert.equal(parsed.events.length,1);
assert.equal(parsed.weights.length,7);
assert.throws(()=>safeData({weights:[],goals:[],nutrition:[]}),/Neplatná struktura/);
assert.ok(serializeCSV([{date:'2026-01-08',kg:66.5}],['date','kg']).includes('66,5'));
console.log('PASS · safe initial state, calculations, import/export, null InBody values');
